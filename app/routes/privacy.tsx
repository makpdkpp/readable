import { env } from "cloudflare:workers";

import type { Route } from "./+types/privacy";
import { pageMeta } from "~/lib/seo";

const POLICY_UPDATED = "28 พฤศจิกายน 2569";

export function meta({ loaderData }: Route.MetaArgs) {
  return pageMeta({
    title: "นโยบายความเป็นส่วนตัว | readable",
    description: "readable เก็บข้อมูลส่วนบุคคลอะไร ใช้ทำอะไร เก็บนานเท่าไร และสิทธิ์ของคุณตาม พ.ร.บ.คุ้มครองข้อมูลส่วนบุคคล (PDPA)",
    url: `${loaderData?.origin ?? ""}/privacy`,
  });
}

export function loader({ request }: Route.LoaderArgs) {
  return { origin: new URL(request.url).origin, contact: env.CONTACT_EMAIL?.trim() || null };
}

